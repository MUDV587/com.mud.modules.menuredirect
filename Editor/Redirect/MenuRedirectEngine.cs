    /// <summary>
    /// 重定向引擎：
    /// 1. 包装代码 —— 依据规则生成到配置指定的目录（文件名固定为
    ///    <c>MenuRedirects.g.cs</c>），每条启用规则对应一个 [MenuItem(新路径)] 包装方法，
    ///    内部通过 <see cref="MenuRedirectInvoker"/> 反射执行原始 [MenuItem] 方法。
    ///    不能使用 EditorApplication.ExecuteMenuItem：原菜单被移除后它会返回 false。
    /// 2. 隐藏原菜单 —— 通过内部 UnityEditor.Menu.RemoveMenuItem 移除"原路径"条目，
    ///    域重载后由 MenuRedirectBootstrap 重放；任何一步失败都只降级、不影响编辑器。
    ///
    /// 保护规则：Unity 内置菜单（File / Edit / Assets / GameObject / Window 等顶级菜单，
    /// 以及由 Unity 程序集声明的子项）一律不隐藏、不搬移，只产出告警。
    /// Tools 根菜单不属于保护范围：它常被第三方/自定义工具使用，允许按规则移除。
    /// </summary>
    internal static class MenuRedirectEngine
    {
        private const string GeneratedFileHeader =
            "// <auto-generated>由 MUD Menu Redirect 生成，请勿手动修改。</auto-generated>";

        public static int LastHiddenCount { get; private set; }
        public static bool LastCodeGenChanged { get; private set; }

        /// <summary>最近一次生成评估中原菜单带快捷键的包装数量；快捷键不会被包装自动复制。</summary>
        public static int LastShortcutCount { get; private set; }

        private static readonly List<string> _lastShortcutTokens = new List<string>();

        /// <summary>上述条目快捷键的去重列表（按出现顺序），如 "_g"、"#%F12"。</summary>
        public static IReadOnlyList<string> LastShortcutTokens => _lastShortcutTokens;
        public static bool LastCodeGenWroteFile { get; private set; }

        /// <summary>最近一次包装代码写入/迁移失败的错误；成功时为 null。</summary>
        public static MenuRedirectText? LastCodeGenError { get; private set; }

        /// <summary>按当前界面语言即时解析的上次隐藏/跳过消息。</summary>
        public static string? LastErrors
        {
            get
            {
                MenuRedirectLanguage language = MenuRedirectLocalization.CurrentLanguage;
                if (_lastErrorsCacheVersion == _lastMessagesVersion &&
                    _lastErrorsCacheLanguage == language)
                {
                    return _lastErrorsCache;
                }

                string? text;
                if (_lastMessages.Count == 0)
                {
                    text = null;
                }
                else
                {
                    var builder = new StringBuilder();
                    for (int i = 0; i < _lastMessages.Count; i++)
                    {
                        if (i > 0)
                            builder.AppendLine();

                        builder.Append(_lastMessages[i].Resolve());
                    }

                    text = builder.ToString();
                }

                _lastErrorsCache = text;
                _lastErrorsCacheVersion = _lastMessagesVersion;
                _lastErrorsCacheLanguage = language;
                return text;
            }
        }

        private static readonly List<MenuRedirectText> _lastMessages =
            new List<MenuRedirectText>();
        private static int _lastMessagesVersion;
        private static int _lastErrorsCacheVersion = -1;
        private static MenuRedirectLanguage _lastErrorsCacheLanguage;
        private static string? _lastErrorsCache;

        private static MenuRegistry? _registry;

        /// <summary>菜单注册表（扫描所有程序集的 [MenuItem] 声明），带缓存。</summary>
        internal static MenuRegistry Registry
        {
            get
            {
                if (_registry == null)
                    _registry = MenuRegistry.Build();

                return _registry;
            }
        }

        /// <summary>规则变更 / 程序集重载后使注册表缓存失效。</summary>
        internal static void InvalidateMenuPathCache()
        {
            _registry = null;
        }

        #region 规则评估（内置菜单保护）

        /// <summary>一条规则的评估结果。</summary>
        internal sealed class RuleEvaluation
        {
            public MenuRedirectRule Rule = null!;
            public string From = string.Empty;
            public string To = string.Empty;

            /// <summary>整条规则是否被保护策略拦下（不执行）。</summary>
            public bool Blocked;

            /// <summary>被拦下的原因（本地化消息）。</summary>
            public MenuRedirectText? Reason;

            /// <summary>需要被隐藏的路径（分支模式=子条目列表；叶子模式=自身）。</summary>
            public List<string> Handle = new List<string>();

            /// <summary>需要生成的搬移映射（原路径 → 新路径）；仅隐藏模式为空。</summary>
            public List<(string child, string target, bool hasValidate)> Moved =
                new List<(string, string, bool)>();

            /// <summary>被跳过的子条目及原因（本地化消息）。</summary>
            public List<(string child, MenuRedirectText reason)> Skipped =
                new List<(string, MenuRedirectText)>();
        }

        /// <summary>
        /// 评估全部启用规则：区分"可执行"与"被内置菜单保护拦下"，
        /// 隐藏与代码生成共用同一份评估结果，保证两边行为一致。
        /// </summary>
        internal static List<RuleEvaluation> Evaluate(MenuRedirectSettings? settings)
        {
            var results = new List<RuleEvaluation>();

            if (ReferenceEquals(settings, null))
                return results;

            MenuRegistry registry = Registry;

            foreach (MenuRedirectRule rule in settings.rules)
            {
                if (rule == null || !rule.enabled)
                    continue;

                string from = MenuRegistry.NormalizePath(rule.fromPath);

                if (from.Length == 0)
                    continue;

                var evaluation = new RuleEvaluation
                {
                    Rule = rule,
                    From = from,
                    To = MenuRegistry.NormalizePath(rule.toPath),
                };

                // 保护 1：源路径本身是 Unity 内置菜单 → 整条规则不执行。
                if (MenuRedirectGuard.IsBuiltIn(from, registry, out MenuRedirectText? fromReason))
                {
                    evaluation.Blocked = true;
                    evaluation.Reason = fromReason;
                    results.Add(evaluation);
                    continue;
                }

                bool isBranch = registry.IsBranchPath(from);
                bool hideOnly = evaluation.To.Length == 0;
                string prefix = from + "/";

                // 旧配置可能绕过设置页校验直接进入域重载重放。非法路径不能生成包装，
                // 目标与源相同/位于源之下时隐藏源还会把新菜单一起移除，因此都必须拒绝执行。
                if (!MenuRedirectValidator.IsValidMenuPath(rule.fromPath, from))
                {
                    evaluation.Blocked = true;
                    evaluation.Reason = L.Text(
                        "engine.invalidPath",
                        (rule.fromPath ?? string.Empty).Trim());
                    results.Add(evaluation);
                    continue;
                }

                if (!hideOnly &&
                    !MenuRedirectValidator.IsValidMenuPath(rule.toPath, evaluation.To))
                {
                    evaluation.Blocked = true;
                    evaluation.Reason = L.Text(
                        "engine.invalidPath",
                        (rule.toPath ?? string.Empty).Trim());
                    results.Add(evaluation);
                    continue;
                }

                if (!hideOnly &&
                    (string.Equals(from, evaluation.To, StringComparison.Ordinal) ||
                     IsUnder(evaluation.To, from)))
                {
                    evaluation.Blocked = true;
                    evaluation.Reason = string.Equals(
                        from,
                        evaluation.To,
                        StringComparison.Ordinal)
                        ? L.Text("engine.targetSameSource", evaluation.To)
                        : L.Text("engine.targetUnderSource", evaluation.To, from);
                    results.Add(evaluation);
                    continue;
                }

                if (isBranch)
                {
                    // 仅隐藏一个包含 Unity 内置子项的容器会移除整棵子树，
                    // 因此这种容器按"完全受保护"处理，不执行任何隐藏。
                    if (hideOnly &&
                        MenuRedirectGuard.IsProtectedContainer(from, registry, out MenuRedirectText? containerReason))
                    {
                        evaluation.Blocked = true;
                        evaluation.Reason = containerReason;
                        results.Add(evaluation);
                        continue;
                    }

                    var protectedPrefixes = new List<string>();

                    foreach (string child in registry.ChildrenOf(from))
                    {
                        if (IsUnderAny(child, protectedPrefixes))
                            continue;

                        // 保护 2：子条目是 Unity 内置 → 跳过它，保留在菜单里。
                        if (MenuRedirectGuard.IsBuiltIn(child, registry, out MenuRedirectText? childReason))
                        {
                            protectedPrefixes.Add(child);
                            evaluation.Skipped.Add((
                                child,
                                childReason ?? L.Text("validation.source.builtIn")));
                            continue;
                        }

                        // 子容器里含 Unity 内置条目时，整个子容器都不能移除/搬移。
                        if (MenuRedirectGuard.IsProtectedContainer(
                                child,
                                registry,
                                out MenuRedirectText? nestedReason))
                        {
                            protectedPrefixes.Add(child);
                            evaluation.Skipped.Add((
                                child,
                                nestedReason ?? L.Text("validation.source.protectedContainer")));
                            continue;
                        }

                        evaluation.Handle.Add(child);

                        if (hideOnly)
                            continue;

                        string target = evaluation.To + "/" + child.Substring(prefix.Length);

                        // 保护 3：新路径与 Unity 内置/已存在菜单冲突 → 跳过该子条目。
                        if (MenuRedirectGuard.IsBuiltIn(target, registry, out _))
                        {
                            evaluation.Handle.Remove(child);
                            evaluation.Skipped.Add((child, L.Text("engine.targetBuiltIn", target)));
                            continue;
                        }

                        if (registry.Contains(target))
                        {
                            evaluation.Handle.Remove(child);
                            evaluation.Skipped.Add((child, L.Text("engine.targetExists", target)));
                            continue;
                        }

                        // 只有能找到静态 [MenuItem] 方法的条目才生成包装；
                        // 动态注册的菜单没有可反射调用的方法。
                        if (!registry.TryGetExecutable(child, out _))
                        {
                            evaluation.Handle.Remove(child);
                            evaluation.Skipped.Add((child, L.Text("engine.noExecutable")));
                            continue;
                        }

                        evaluation.Moved.Add((child, target, registry.HasValidate(child)));
                    }

                    if (!hideOnly && evaluation.Moved.Count == 0)
                    {
                        // 分支下没有找到可搬移条目：不要移除父级，避免误删动态注册的整棵子树。
                        evaluation.Skipped.Add((from, L.Text("engine.noMovableChildren")));
                    }
                }
                else
                {
                    // 叶子路径下可能仍带有子菜单；整体移除会连带删除受保护子项。
                    if (MenuRedirectGuard.IsProtectedContainer(from, registry, out MenuRedirectText? containerReason))
                    {
                        evaluation.Blocked = true;
                        evaluation.Reason = containerReason;
                        results.Add(evaluation);
                        continue;
                    }

                    evaluation.Handle.Add(from);

                    if (hideOnly)
                    {
                        results.Add(evaluation);
                        continue;
                    }

                    // 保护 3：叶子模式的新路径不能落在 Unity 内置/已存在菜单上。
                    if (MenuRedirectGuard.IsBuiltIn(evaluation.To, registry, out _))
                    {
                        evaluation.Handle.Clear();
                        evaluation.Blocked = true;
                        evaluation.Reason = L.Text("engine.targetBuiltIn", evaluation.To);
                        results.Add(evaluation);
                        continue;
                    }

                    if (registry.Contains(evaluation.To))
                    {
                        evaluation.Handle.Clear();
                        evaluation.Blocked = true;
                        evaluation.Reason = L.Text("engine.targetExists", evaluation.To);
                        results.Add(evaluation);
                        continue;
                    }

                    if (!registry.TryGetExecutable(from, out _))
                    {
                        evaluation.Handle.Clear();
                        evaluation.Blocked = true;
                        evaluation.Reason = L.Text("engine.noExecutableLeaf");
                        results.Add(evaluation);
                        continue;
                    }

                    evaluation.Moved.Add((from, evaluation.To, registry.HasValidate(from)));
                }

                results.Add(evaluation);
            }

            return results;
        }

        private static bool IsUnder(string path, string root)
        {
            if (string.IsNullOrEmpty(path) || string.IsNullOrEmpty(root))
                return false;

            return string.Equals(path, root, StringComparison.Ordinal) ||
                   path.StartsWith(root + "/", StringComparison.Ordinal);
        }

        private static bool IsUnderAny(string path, List<string> roots)
        {
            for (int i = 0; i < roots.Count; i++)
            {
                if (path.StartsWith(roots[i] + "/", StringComparison.Ordinal))
                    return true;
            }

            return false;
        }

