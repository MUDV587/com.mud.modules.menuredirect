        #region 隐藏原菜单

        /// <summary>尝试移除一个条目并复核结果。</summary>
        private static bool TryRemove(
            MenuRegistry registry,
            string target,
            List<MenuRedirectText> messages,
            ref int hidden)
        {
            // 菜单显示路径去掉了助记符下划线，RemoveMenuItem 用原始路径更可靠。
            string removalPath = registry.GetRemovalPath(target);
            MenuRedirectText detail = string.Equals(removalPath, target, StringComparison.Ordinal)
                ? L.Text("engine.pathOnly", target)
                : L.Text("engine.originalPath", target, removalPath);

            bool canCheck = MenuRedirectBridge.CanCheckExists;
            bool existed = !canCheck || MenuRedirectBridge.MenuItemExists(removalPath);

            if (!MenuRedirectBridge.RemoveMenuItem(removalPath))
            {
                messages.Add(L.Text("engine.cannotHide", detail));
                return false;
            }

            if (canCheck && MenuRedirectBridge.MenuItemExists(removalPath))
            {
                messages.Add(L.Text("engine.stillExists", detail));
                return false;
            }

            if (canCheck && !existed)
            {
                // 已经处于隐藏状态（重复应用，或其它插件已移除）。视为已达成目标，不重复计数。
                return true;
            }

            hidden++;
            return true;
        }

        /// <summary>仅执行隐藏部分（供域重载后重放）。</summary>
        public static void HideOriginals(MenuRedirectSettings? settings)
        {
            List<RuleEvaluation> evaluations = Evaluate(settings);
            if (TryHideOriginals(settings, evaluations, out MenuRedirectText? reason))
                return;

            if (ReferenceEquals(settings, null))
                return;

            _lastMessages.Add(reason ??
                              L.Text("engine.generatedStale", GetGeneratedPath(settings)));
            _lastMessagesVersion++;
            Debug.LogWarning("[MenuRedirect] " + LastErrors);
        }

        /// <summary>
        /// 单次评估后的隐藏入口：先复核包装代码，再复用同一份评估结果执行隐藏。
        /// 返回 false 时 <paramref name="reason"/> 说明包装代码为何尚未就绪。
        /// </summary>
        public static bool TryHideOriginals(
            MenuRedirectSettings? settings,
            out MenuRedirectText? reason)
        {
            List<RuleEvaluation> evaluations = Evaluate(settings);
            return TryHideOriginals(settings, evaluations, out reason);
        }

        internal static bool TryHideOriginals(
            MenuRedirectSettings? settings,
            List<RuleEvaluation> evaluations,
            out MenuRedirectText? reason)
        {
            LastHiddenCount = 0;
            _lastMessages.Clear();
            _lastMessagesVersion++;
            reason = null;

            if (ReferenceEquals(settings, null))
                return false;

            if (!IsGeneratedCodeReady(settings, evaluations, out reason))
                return false;

            HideEvaluated(settings, evaluations);
            return true;
        }

        private static void HideEvaluated(
            MenuRedirectSettings settings,
            List<RuleEvaluation> evaluations)
        {
            var messages = new List<MenuRedirectText>();
            int hidden = 0;
            int skipped = 0;

            if (!MenuRedirectBridge.Available)
            {
                _lastMessages.Add(L.Text(
                    "engine.apiUnavailable",
                    MenuRedirectBridge.UnavailableReason ?? L.Text("bridge.menuTypeMissing")));
                _lastMessagesVersion++;
                Debug.LogWarning("[MenuRedirect] " + LastErrors);
                return;
            }

            MenuRegistry registry = Registry;
            var processed = new HashSet<string>(StringComparer.Ordinal);

            foreach (RuleEvaluation evaluation in evaluations)
            {
                if (evaluation.Blocked)
                {
                    skipped++;
                    messages.Add(L.Text(
                        "engine.skipped",
                        evaluation.From,
                        evaluation.Reason ?? L.Text("validation.source.builtIn")));
                    continue;
                }

                if (!processed.Add(evaluation.From))
                    continue;

                foreach ((string child, MenuRedirectText reason) in evaluation.Skipped)
                {
                    skipped++;
                    messages.Add(L.Text("engine.skipped", child, reason));
                }

                bool isBranch = registry.IsBranchPath(evaluation.From);

                // 仅隐藏的分支即使注册表里没有子项（例如动态注册的菜单）也直接移除父级；
                // 重定向分支没有可生成包装的子项时，上面的评估已经把它标记为跳过。
                if (evaluation.Handle.Count == 0 &&
                    evaluation.Skipped.Count == 0 &&
                    !(isBranch && evaluation.To.Length == 0))
                {
                    messages.Add(L.Text("engine.noRemovable", evaluation.From));
                    continue;
                }

                if (evaluation.Skipped.Count > 0 && evaluation.Handle.Count == 0)
                    continue;

                string parentRemovalPath = registry.GetRemovalPath(evaluation.From);
                bool parentExists = !MenuRedirectBridge.CanCheckExists ||
                                    MenuRedirectBridge.MenuItemExists(parentRemovalPath);

                bool removedAny = false;

                if (isBranch && evaluation.Skipped.Count == 0 && parentExists)
                {
                    // 与已验证的移除方式一致：直接移除父级，一次清掉整棵子树。
                    removedAny = TryRemove(registry, evaluation.From, messages, ref hidden);
                }
                else
                {
                    // 有内置/不可执行子项被跳过时，只能逐个移除允许的条目，保留父级容器。
                    foreach (string path in evaluation.Handle)
                        removedAny |= TryRemove(registry, path, messages, ref hidden);
                }

                if (!removedAny && evaluation.Skipped.Count == 0)
                    messages.Add(L.Text("engine.hideFailed", evaluation.From));
            }

            // 刷新菜单界面。
            // 注意：这里绝不能调用 Menu.RebuildAllMenus()——它会按 [MenuItem] 特性重新注册所有条目，
            // 把刚移除的菜单原样恢复（隐藏失效的根因）。
            MenuRedirectBridge.RefreshMenus();

            LastHiddenCount = hidden;
            _lastMessages.Clear();
            _lastMessages.AddRange(messages);
            _lastMessagesVersion++;

            // 没有启用规则、或原菜单已经处于隐藏状态时保持安静，避免每次域重载刷日志。
            if (hidden == 0 && skipped == 0 && messages.Count == 0)
                return;

            var summary = new StringBuilder(L.F("engine.summary", hidden, skipped));

            if (messages.Count > 0)
            {
                summary.AppendLine();
                for (int i = 0; i < messages.Count; i++)
                {
                    if (i > 0)
                        summary.AppendLine();

                    summary.Append(messages[i].Resolve());
                }
            }

            if (skipped > 0)
                Debug.LogWarning(summary.ToString());
            else
                Debug.Log(summary.ToString());
        }

        #endregion

        /// <summary>
        /// 应用前的包装代码事务：先写文件但不隐藏菜单，调用方保存配置成功后再
        /// <see cref="GeneratedCodeTransaction.Commit"/>；保存失败则
        /// <see cref="GeneratedCodeTransaction.Rollback"/> 恢复原文件。
        /// 包装代码有变化时必须等待编译后的域重载再隐藏原菜单。
        /// </summary>
        public static GeneratedCodeTransaction? PrepareApply(MenuRedirectSettings settings)
        {
            InvalidateMenuPathCache();
            LastCodeGenError = null;
            LastCodeGenWroteFile = false;
            LastCodeGenChanged = false;
            LastHiddenCount = 0;
            LastShortcutCount = 0;
            _lastShortcutTokens.Clear();
            _lastMessages.Clear();
            _lastMessagesVersion++;

            // 即使调用方绕过设置页验证，也不允许把包装代码写到 Assets 的 Editor 目录之外。
            MenuRedirectText? folderError = ValidateGeneratedFolder(settings.generatedCodeFolder);
            if (folderError != null)
            {
                LastCodeGenError = folderError;
                return null;
            }

            return PrepareGeneratedCode(settings);
        }

        /// <summary>包装代码文件事务；只有配置保存成功后才能提交。</summary>
        internal sealed class GeneratedCodeTransaction
        {
            private readonly MenuRedirectSettings _settings;
            private readonly string _oldPath;
            private readonly string _previousLastPath;
            private readonly string _fullNewPath;
            private readonly string _fullOldPath;
            private readonly bool _newExisted;
            private readonly bool _oldExists;
            private readonly bool _sameAsset;
            private readonly bool _wrote;
            private readonly bool _changed;
            private readonly string? _newBackup;
            private bool _finished;

            internal GeneratedCodeTransaction(
                MenuRedirectSettings settings,
                string oldPath,
                string previousLastPath,
                string fullNewPath,
                string fullOldPath,
                bool newExisted,
                bool oldExists,
                bool sameAsset,
                bool wrote,
                bool changed,
                string? newBackup)
            {
                _settings = settings;
                _oldPath = oldPath;
                _previousLastPath = previousLastPath;
                _fullNewPath = fullNewPath;
                _fullOldPath = fullOldPath;
                _newExisted = newExisted;
                _oldExists = oldExists;
                _sameAsset = sameAsset;
                _wrote = wrote;
                _changed = changed;
                _newBackup = newBackup;
            }

            internal bool Changed => _changed;
            internal bool WroteFile => _wrote;

            /// <summary>保存配置失败时恢复写入前的文件状态和 lastGeneratedCodePath。</summary>
            internal void Rollback()
            {
                if (_finished)
                    return;

                _finished = true;
                _settings.lastGeneratedCodePath = _previousLastPath;

                if (!_wrote)
                    return;

                try
                {
                    if (_newExisted)
                    {
                        File.WriteAllText(
                            _fullNewPath,
                            _newBackup ?? string.Empty,
                            new UTF8Encoding(false));
                    }
                    else if (File.Exists(_fullNewPath))
                    {
                        File.Delete(_fullNewPath);
                        string metaPath = _fullNewPath + ".meta";
                        if (File.Exists(metaPath))
                            File.Delete(metaPath);
                    }
                }
                catch (Exception exception)
                {
                    Debug.LogWarning(L.F("engine.rollbackFailed", exception.Message));
                }
            }

            /// <summary>配置保存成功后删除旧包装文件并导入新代码；失败时保留错误供界面显示。</summary>
            internal bool Commit()
            {
                if (_finished)
                    return LastCodeGenError == null;

                if (!_sameAsset && _oldExists)
                {
                    // Prepare 与 Commit 之间可能发生外部编辑；删除前再确认一次生成头，
                    // 绝不删除已被替换成用户文件的旧路径。
                    if (File.Exists(_fullOldPath) && !IsGeneratedCodeFile(_fullOldPath))
                    {
                        LastCodeGenError = L.Text(
                            "engine.oldGeneratedNotGenerated",
                            _oldPath);
                        return false;
                    }

                    bool deleted = false;
                    try
                    {
                        deleted = AssetDatabase.DeleteAsset(_oldPath);
                        if (!deleted && File.Exists(_fullOldPath))
                        {
                            File.Delete(_fullOldPath);
                            string metaPath = _fullOldPath + ".meta";
                            if (File.Exists(metaPath))
                                File.Delete(metaPath);
                            deleted = !File.Exists(_fullOldPath);
                        }
                    }
                    catch (Exception exception)
                    {
                        Debug.LogWarning(L.F(
                            "engine.oldGeneratedDeleteFailed",
                            _oldPath + " (" + exception.Message + ")"));
                    }

                    if (!deleted)
                    {
                        LastCodeGenError = L.Text(
                            "engine.oldGeneratedDeleteFailed",
                            _oldPath);
                        // 保持 _finished=false：调用方必须撤销新文件并把路径指回旧文件，
                        // 否则两个包装文件会同时存在，产生重复类编译错误。
                        return false;
                    }
                }

                // 旧文件已删除（或本来就无需删除），此后不能再回滚新文件。
                _finished = true;

                if (_changed)
                {
                    AssetDatabase.Refresh();
                    Debug.Log(L.T("engine.codegenUpdated"));
                }

                return true;
            }

            /// <summary>
            /// 配置已保存但旧包装文件删除失败时调用：删除本次写入的新文件，
            /// 把路径指回旧文件并刷新资产库，避免两个包装类同时存在。
            /// 调用方应随后再次保存配置，使磁盘上的路径与内存一致。
            /// </summary>
            internal void RollbackAfterCommitFailure()
            {
                if (_finished)
                    return;

                _finished = true;
                _settings.lastGeneratedCodePath = _previousLastPath;

                try
                {
                    if (!_sameAsset && File.Exists(_fullNewPath))
                    {
                        File.Delete(_fullNewPath);
                        string metaPath = _fullNewPath + ".meta";
                        if (File.Exists(metaPath))
                            File.Delete(metaPath);
                    }
                }
                catch (Exception exception)
                {
                    Debug.LogWarning(L.F("engine.rollbackFailed", exception.Message));
                }
            }
        }

