        public static string BuildGeneratedContent(MenuRedirectSettings? settings)
        {
            return BuildGeneratedContent(settings, null);
        }

        /// <summary>
        /// 使用调用方已完成的评估结果生成包装代码，避免域重载检查中重复评估规则。
        /// </summary>
        internal static string BuildGeneratedContent(
            MenuRedirectSettings? settings,
            List<RuleEvaluation>? evaluations)
        {
            evaluations ??= Evaluate(settings);

            var sb = new StringBuilder();
            sb.AppendLine(GeneratedFileHeader);
            sb.AppendLine("// 规则内容保存在 " + MenuRedirectSettings.ProjectSettingsPath);
            sb.AppendLine("// 包装方法通过 MenuRedirectInvoker 反射执行原始 [MenuItem] 方法。");
            sb.AppendLine("#if UNITY_EDITOR");
            sb.AppendLine("using UnityEditor;");
            sb.AppendLine();
            sb.AppendLine("namespace MUD.MenuRedirects");
            sb.AppendLine("{");
            sb.AppendLine("    internal static class MenuRedirects_Generated");
            sb.AppendLine("    {");

            int index = 0;
            LastShortcutCount = 0;
            _lastShortcutTokens.Clear();

            foreach (RuleEvaluation evaluation in evaluations)
            {
                if (evaluation.Blocked)
                {
                    // 生成代码注释保持固定中文，避免切换界面语言后包装文件内容变化。
                    sb.AppendLine(
                        "        // 已跳过: " + evaluation.From + " —— " +
                        (evaluation.Reason?.Resolve(MenuRedirectLanguage.Chinese) ?? string.Empty));
                    sb.AppendLine();
                    continue;
                }

                foreach ((string child, MenuRedirectText reason) in evaluation.Skipped)
                {
                    sb.AppendLine(
                        "        // 已跳过: " + child + " —— " +
                        reason.Resolve(MenuRedirectLanguage.Chinese));
                }

                if (evaluation.Skipped.Count > 0)
                    sb.AppendLine();

                foreach ((string child, string target, bool hasValidate) in evaluation.Moved)
                {
                    string? shortcut = Registry.FindShortcut(child);
                    if (shortcut != null)
                    {
                        LastShortcutCount++;
                        if (!_lastShortcutTokens.Contains(shortcut))
                            _lastShortcutTokens.Add(shortcut);
                    }

                    EmitPair(
                        sb,
                        ref index,
                        child + " -> " + target,
                        child,
                        target,
                        evaluation.Rule.priority,
                        hasValidate,
                        shortcut);
                }
            }

            sb.AppendLine("    }"); // class
            sb.AppendLine("}");     // namespace
            sb.AppendLine("#endif");

            return sb.ToString();
        }

        /// <summary>向包装代码中写入一条 [MenuItem] 包装：新路径调用原始方法。</summary>
        private static void EmitPair(
            StringBuilder sb,
            ref int index,
            string description,
            string fromPath,
            string toPath,
            int priority,
            bool hasValidate,
            string? shortcut)
        {
            string methodIndex = index.ToString();

            sb.AppendLine("        // " + description);
            if (shortcut != null)
            {
                // 与"已跳过"注释一致保持固定中文，避免切换界面语言后包装文件内容变化。
                sb.AppendLine(
                    "        // 原菜单快捷键: " + shortcut +
                    " —— 包装不会自动复制，请手动为目标菜单添加。");
            }

            sb.AppendLine("        [MenuItem(\"" + CSharpEscape(toPath) + "\", false, " + priority + ")]");
            sb.AppendLine("        private static void Redirect_" + methodIndex + "()");
            sb.AppendLine("        {");
            sb.AppendLine("            global::MUD.Modules.MenuRedirect.MenuRedirectInvoker.Execute(\"" +
                          CSharpEscape(fromPath) + "\");");
            sb.AppendLine("        }");
            sb.AppendLine();

            if (hasValidate)
            {
                sb.AppendLine("        [MenuItem(\"" + CSharpEscape(toPath) + "\", true, " + priority + ")]");
                sb.AppendLine("        private static bool Redirect_" + methodIndex + "_Validate()");
                sb.AppendLine("        {");
                sb.AppendLine("            return global::MUD.Modules.MenuRedirect.MenuRedirectInvoker.Validate(\"" +
                              CSharpEscape(fromPath) + "\");");
                sb.AppendLine("        }");
                sb.AppendLine();
            }

            index++;
        }

        /// <summary>比较配置路径上的包装代码和当前规则；不一致返回 true（需要重编译）。</summary>
        public static bool HasPendingCodeChanges(MenuRedirectSettings? settings)
        {
            return HasPendingCodeChanges(settings, null);
        }

        internal static bool HasPendingCodeChanges(
            MenuRedirectSettings? settings,
            List<RuleEvaluation>? evaluations)
        {
            string current = BuildGeneratedContent(settings, evaluations);
            string fullPath = ToFullPath(GetGeneratedPath(settings));

            if (!File.Exists(fullPath))
                return ContainsRule(settings);

            try
            {
                string onDisk = File.ReadAllText(fullPath);
                return Normalize(onDisk) != Normalize(current);
            }
            catch
            {
                return true;
            }
        }

        /// <summary>把已启用规则中的路径规范化为菜单显示路径（去快捷键、助记符下划线）。</summary>
        public static void NormalizeRulePaths(MenuRedirectSettings settings)
        {
            if (settings?.rules == null)
                return;

            foreach (MenuRedirectRule rule in settings.rules)
            {
                if (rule == null)
                    continue;

                rule.fromPath = MenuRegistry.NormalizePath(rule.fromPath);
                rule.toPath = MenuRegistry.NormalizePath(rule.toPath);
            }
        }

        private static bool ContainsRule(MenuRedirectSettings? settings)
        {
            if (ReferenceEquals(settings, null))
                return false;

            foreach (MenuRedirectRule rule in settings.rules)
            {
                if (rule != null && rule.enabled &&
                    !string.IsNullOrWhiteSpace(rule.fromPath) && !string.IsNullOrWhiteSpace(rule.toPath))
                    return true;
            }

            return false;
        }

        private static bool ContainsRedirectRule(MenuRedirectSettings? settings)
        {
            return ContainsRule(settings);
        }

        /// <summary>
        /// 域重载后隐藏原菜单前的安全检查：生成的包装代码必须存在且与当前规则一致。
        /// 编译失败或上次 Apply 未成功时，宁可暂不隐藏，也不能让原菜单和新菜单同时消失。
        /// </summary>
        public static bool IsGeneratedCodeReady(
            MenuRedirectSettings? settings,
            out MenuRedirectText? reason)
        {
            return IsGeneratedCodeReady(settings, null, out reason);
        }

        internal static bool IsGeneratedCodeReady(
            MenuRedirectSettings? settings,
            List<RuleEvaluation>? evaluations,
            out MenuRedirectText? reason)
        {
            reason = null;

            string generatedPath = GetGeneratedPath(settings);
            string fullPath = ToFullPath(generatedPath);
            bool hasRedirect = ContainsRedirectRule(settings);

            if (!File.Exists(fullPath))
            {
                if (!hasRedirect)
                    return true;

                reason = L.Text("engine.generatedMissing", generatedPath);
                return false;
            }

            if (!IsGeneratedCodeFile(fullPath))
            {
                reason = L.Text("engine.generatedNotGenerated", generatedPath);
                return false;
            }

            if (HasPendingCodeChanges(settings, evaluations))
            {
                reason = L.Text("engine.generatedStale", generatedPath);
                return false;
            }

            return true;
        }

        private static string Normalize(string text)
        {
            return text.Replace("\r\n", "\n").Trim();
        }

        /// <summary>规范化生成目录；空值回退到默认目录，并统一使用正斜杠。</summary>
        public static string NormalizeGeneratedFolder(string? folder)
        {
            string value = string.IsNullOrWhiteSpace(folder)
                ? MenuRedirectSettings.DefaultGeneratedCodeFolder
                : folder!.Trim().Replace('\\', '/');

            while (value.Contains("//"))
                value = value.Replace("//", "/");

            value = value.TrimEnd('/');
            string generatedFileName = "/" + MenuRedirectSettings.GeneratedCodeFileName;
            if (value.EndsWith(generatedFileName, StringComparison.OrdinalIgnoreCase))
            {
                value = value.Substring(0, value.Length - generatedFileName.Length);
            }

            return value;
        }

        public static string GetGeneratedFolder(MenuRedirectSettings? settings)
        {
            return NormalizeGeneratedFolder(settings?.generatedCodeFolder);
        }

        public static string GetGeneratedPath(MenuRedirectSettings? settings)
        {
            return GetGeneratedPath(settings?.generatedCodeFolder);
        }

        public static string GetGeneratedPath(string? folder)
        {
            return NormalizeGeneratedFolder(folder) + "/" +
                   MenuRedirectSettings.GeneratedCodeFileName;
        }

        /// <summary>校验生成目录；返回 null 表示通过，否则返回可直接显示/重新本地化的错误。</summary>
        public static MenuRedirectText? ValidateGeneratedFolder(string? folder)
        {
            string normalized = NormalizeGeneratedFolder(folder);
            if (string.Equals(normalized, "Assets", StringComparison.Ordinal))
                return L.Text("apply.error.generatedFolder.notEditor");

            if (!normalized.StartsWith("Assets/", StringComparison.Ordinal))
                return L.Text("apply.error.generatedFolder.outsideAssets");

            if (normalized.EndsWith(".cs", StringComparison.OrdinalIgnoreCase))
                return L.Text("apply.error.generatedFolder.invalid", normalized);

            string relative = normalized.Substring("Assets/".Length);
            string[] segments = relative.Split('/');
            bool hasEditorSegment = false;

            for (int i = 0; i < segments.Length; i++)
            {
                string segment = segments[i];
                if (segment.Length == 0 ||
                    string.Equals(segment, ".", StringComparison.Ordinal) ||
                    string.Equals(segment, "..", StringComparison.Ordinal))
                {
                    return L.Text("apply.error.generatedFolder.invalid", normalized);
                }

                if (string.Equals(segment, "Editor", StringComparison.Ordinal))
                    hasEditorSegment = true;
            }

            if (!hasEditorSegment)
                return L.Text("apply.error.generatedFolder.notEditor");

            string generatedPath = GetGeneratedPath(normalized);
            string fullFolder = ToFullPath(normalized);
            string fullGeneratedPath = ToFullPath(generatedPath);

            if (File.Exists(fullFolder))
                return L.Text("apply.error.generatedFolder.folderIsFile", normalized);

            if (Directory.Exists(fullGeneratedPath))
                return L.Text("apply.error.generatedFolder.targetIsFolder", generatedPath);

            if (File.Exists(fullGeneratedPath) && !IsGeneratedCodeFile(fullGeneratedPath))
                return L.Text("apply.error.generatedFolder.fileExists", generatedPath);

            return null;
        }

        private static GeneratedCodeTransaction? PrepareGeneratedCode(MenuRedirectSettings settings)
        {
            string content = BuildGeneratedContent(settings);
            string generatedPath = GetGeneratedPath(settings);
            string previousPath = GetLastGeneratedPath(settings);
            string fullGeneratedPath = ToFullPath(generatedPath);
            string fullPreviousPath = ToFullPath(previousPath);
            bool sameAsset = AreSameAssetPath(previousPath, generatedPath);
            bool oldPathIsAsset = IsAssetPath(previousPath);
            bool oldExists = oldPathIsAsset && !sameAsset && File.Exists(fullPreviousPath);
            bool hasRules = ContainsRule(settings);
            bool newExisted = false;
            bool wrote = false;
            string? newBackup = null;

            try
            {
                if (Directory.Exists(fullGeneratedPath))
                {
                    LastCodeGenError = L.Text(
                        "apply.error.generatedFolder.targetIsFolder",
                        generatedPath);
                    return null;
                }

                newExisted = File.Exists(fullGeneratedPath);
                if (newExisted && !IsGeneratedCodeFile(fullGeneratedPath))
                {
                    LastCodeGenError = L.Text(
                        "apply.error.generatedFolder.fileExists",
                        generatedPath);
                    return null;
                }

                if (oldExists && !IsGeneratedCodeFile(fullPreviousPath))
                {
                    LastCodeGenError = L.Text(
                        "engine.oldGeneratedNotGenerated",
                        previousPath);
                    return null;
                }

                string? conflictingPath = FindConflictingGeneratedWrapper(
                    generatedPath,
                    previousPath);
                if (!string.IsNullOrEmpty(conflictingPath))
                {
                    LastCodeGenError = L.Text(
                        "engine.conflictingGenerated",
                        conflictingPath!);
                    return null;
                }

                bool changed = oldExists;

                if (newExisted)
                {
                    string onDisk = File.ReadAllText(fullGeneratedPath);
                    if (Normalize(onDisk) != Normalize(content))
                    {
                        newBackup = onDisk;
                        WriteGeneratedCode(generatedPath, content);
                        wrote = true;
                        changed = true;
                    }
                }
                else if (hasRules)
                {
                    WriteGeneratedCode(generatedPath, content);
                    wrote = true;
                    changed = true;
                }

                if (!oldPathIsAsset && !string.IsNullOrWhiteSpace(previousPath) &&
                    !sameAsset)
                {
                    Debug.LogWarning(L.F("engine.oldGeneratedKept", previousPath));
                }

                settings.lastGeneratedCodePath = generatedPath;
                LastCodeGenWroteFile = wrote;
                LastCodeGenChanged = changed;

                return new GeneratedCodeTransaction(
                    settings,
                    previousPath,
                    previousPath,
                    fullGeneratedPath,
                    fullPreviousPath,
                    newExisted,
                    oldExists,
                    sameAsset,
                    wrote,
                    changed,
                    newBackup);
            }
            catch (Exception exception)
            {
                if (wrote)
                {
                    try
                    {
                        if (newExisted)
                        {
                            File.WriteAllText(
                                fullGeneratedPath,
                                newBackup ?? string.Empty,
                                new UTF8Encoding(false));
                        }
                        else if (File.Exists(fullGeneratedPath))
                        {
                            File.Delete(fullGeneratedPath);
                            string metaPath = fullGeneratedPath + ".meta";
                            if (File.Exists(metaPath))
                                File.Delete(metaPath);
                        }
                    }
                    catch
                    {
                        // 原始写入异常优先报告；回滚失败只作为降级。
                    }
                }

                settings.lastGeneratedCodePath = previousPath;
                LastCodeGenWroteFile = false;
                LastCodeGenChanged = false;
                LastCodeGenError = L.Text("engine.writeFailed", exception.Message);
                Debug.LogWarning(LastCodeGenError.Resolve());
                return null;
            }
        }

        /// <summary>
        /// 防止项目里同时存在两个带同一生成类的包装文件。正常迁移的旧/新路径会跳过，
        /// 其它位置残留的包装文件会在 Apply 前直接拦截，避免编译期重复类错误。
        /// </summary>
        private static string? FindConflictingGeneratedWrapper(
            string generatedPath,
            string previousPath)
        {
            try
            {
                string assetsRoot = ToFullPath("Assets");
                if (!Directory.Exists(assetsRoot))
                    return null;

                foreach (string fullPath in Directory.EnumerateFiles(
                             assetsRoot,
                             MenuRedirectSettings.GeneratedCodeFileName,
                             SearchOption.AllDirectories))
                {
                    string assetPath = ToAssetPath(fullPath);
                    if (assetPath.Length == 0 ||
                        AreSameAssetPath(assetPath, generatedPath) ||
                        AreSameAssetPath(assetPath, previousPath))
                    {
                        continue;
                    }

                    if (IsGeneratedCodeFile(fullPath))
                        return assetPath;
                }
            }
            catch
            {
                // 扫描失败不阻断正常写入；目标位置本身的冲突检查仍然有效。
            }

            return null;
        }

        private static string ToAssetPath(string fullPath)
        {
            string assetsRoot = ToFullPath("Assets");
            string rootPrefix = assetsRoot.TrimEnd(
                Path.DirectorySeparatorChar,
                Path.AltDirectorySeparatorChar) + Path.DirectorySeparatorChar;

            if (!fullPath.StartsWith(rootPrefix, StringComparison.OrdinalIgnoreCase))
                return string.Empty;

            return "Assets/" + fullPath
                .Substring(rootPrefix.Length)
                .Replace('\\', '/');
        }

        private static bool AreSameAssetPath(string first, string second)
        {
            if (string.Equals(first, second, StringComparison.Ordinal))
                return true;

            if (string.IsNullOrWhiteSpace(first) || string.IsNullOrWhiteSpace(second))
                return false;

            return string.Equals(
                first.Replace('\\', '/').TrimEnd('/'),
                second.Replace('\\', '/').TrimEnd('/'),
                StringComparison.OrdinalIgnoreCase);
        }

        private static string GetLastGeneratedPath(MenuRedirectSettings? settings)
        {
            string? path = settings?.lastGeneratedCodePath;
            if (string.IsNullOrWhiteSpace(path))
                return MenuRedirectSettings.DefaultGeneratedCodePath;

            return path!.Trim().Replace('\\', '/');
        }

        private static void WriteGeneratedCode(string generatedPath, string content)
        {
            int slash = generatedPath.LastIndexOf('/');
            if (slash <= 0)
                throw new InvalidOperationException("Invalid generated code path: " + generatedPath);

            string folder = generatedPath.Substring(0, slash);
            EnsureAssetFolder(folder);
            File.WriteAllText(ToFullPath(generatedPath), content, new UTF8Encoding(false));
        }

        private static void EnsureAssetFolder(string folder)
        {
            string fullFolder = ToFullPath(folder);

            // AssetDatabase can keep a folder marked as valid after it was deleted
            // outside Unity (tests, source control, or the OS). Recreate the physical
            // folder instead of returning early and failing while writing the file.
            if (AssetDatabase.IsValidFolder(folder))
            {
                if (!Directory.Exists(fullFolder))
                {
                    Directory.CreateDirectory(fullFolder);
                    AssetDatabase.ImportAsset(folder, ImportAssetOptions.ForceUpdate);
                }

                return;
            }

            string[] parts = folder.Split('/');
            if (parts.Length < 2 ||
                !string.Equals(parts[0], "Assets", StringComparison.Ordinal))
            {
                throw new InvalidOperationException("Generated code folder is outside Assets: " + folder);
            }

            string current = parts[0];
            for (int i = 1; i < parts.Length; i++)
            {
                if (parts[i].Length == 0)
                    continue;

                string next = current + "/" + parts[i];
                string fullNext = ToFullPath(next);
                if (AssetDatabase.IsValidFolder(next))
                {
                    if (!Directory.Exists(fullNext))
                    {
                        Directory.CreateDirectory(fullNext);
                        AssetDatabase.ImportAsset(next, ImportAssetOptions.ForceUpdate);
                    }
                }
                else
                {
                    string fullCurrent = ToFullPath(current);
                    if (!Directory.Exists(fullCurrent))
                        Directory.CreateDirectory(fullCurrent);

                    string guid = AssetDatabase.CreateFolder(current, parts[i]);
                    if (string.IsNullOrEmpty(guid))
                    {
                        // Fall back to the file system when the AssetDatabase parent
                        // entry is stale, then let Unity import the new folder.
                        Directory.CreateDirectory(fullNext);
                        AssetDatabase.ImportAsset(next, ImportAssetOptions.ForceUpdate);
                    }

                    if (!AssetDatabase.IsValidFolder(next) && !Directory.Exists(fullNext))
                        throw new IOException("Failed to create folder: " + next);
                }

                current = next;
            }
        }

        internal static bool IsGeneratedCodeFile(string fullPath)
        {
            try
            {
                using (var reader = new StreamReader(fullPath))
                {
                    string? firstLine = reader.ReadLine();
                    return firstLine != null &&
                           string.Equals(
                               firstLine.TrimStart('\uFEFF').Trim(),
                               GeneratedFileHeader,
                               StringComparison.Ordinal);
                }
            }
            catch
            {
                return false;
            }
        }

        internal static bool IsAssetPath(string assetPath)
        {
            if (!assetPath.StartsWith("Assets/", StringComparison.Ordinal))
                return false;

            string[] segments = assetPath.Split('/');
            for (int i = 1; i < segments.Length; i++)
            {
                string segment = segments[i];
                if (segment.Length == 0 ||
                    string.Equals(segment, ".", StringComparison.Ordinal) ||
                    string.Equals(segment, "..", StringComparison.Ordinal))
                {
                    return false;
                }
            }

            return true;
        }

        internal static string ToFullPath(string assetPath)
        {
            string projectRoot = Directory.GetParent(Application.dataPath)?.FullName ?? string.Empty;
            if (projectRoot.Length == 0)
                return assetPath;

            return Path.Combine(
                projectRoot,
                assetPath.Replace('/', Path.DirectorySeparatorChar));
        }

        private static string CSharpEscape(string text)
        {
            if (string.IsNullOrEmpty(text))
                return string.Empty;

            return text
                .Replace("\\", "\\\\")
                .Replace("\"", "\\\"")
                .Replace("\r", "\\r")
                .Replace("\n", "\\n");
        }

